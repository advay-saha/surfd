"""End-to-end CLI behaviour, run in-process with an isolated HOME."""

from __future__ import annotations

from pathlib import Path

import pytest

from surfd import cli, config, paths


def run(*argv: str) -> int:
    return cli.main(list(argv))


def test_first_command_creates_config(env: Path) -> None:
    assert not paths.user_config().exists()
    assert run("get", "theme.name") == 0
    assert paths.user_config().exists()


def test_accent_set_and_reset(env: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert run("accent", "#88c0d0") == 0
    assert config.load()["theme"]["accent"] == "#88c0d0"
    assert "accent set to #88c0d0" in capsys.readouterr().out
    assert (paths.generated_dir() / "waybar" / "style.css").read_text().count("#88c0d0") > 0
    assert run("accent", "reset") == 0
    assert config.load()["theme"]["accent"] == ""


def test_bad_accent_changes_nothing(env: Path, capsys: pytest.CaptureFixture[str]) -> None:
    run("init", "-q")
    before = paths.user_config().read_text()
    assert run("accent", "blue") == 1
    assert "not a colour" in capsys.readouterr().err
    assert paths.user_config().read_text() == before


def test_theme_set_with_variant(env: Path) -> None:
    assert run("theme", "set", "driftwood", "--variant", "light") == 0
    cfg = config.load()
    assert (cfg["theme"]["name"], cfg["theme"]["variant"]) == ("driftwood", "light")
    assert run("theme", "variant", "toggle") == 0
    assert config.load()["theme"]["variant"] == "dark"
    assert run("theme", "set", "nope") == 1


def test_theme_list(env: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert run("theme", "list") == 0
    out = capsys.readouterr().out
    assert "tide" in out and "driftwood" in out and "kelp" in out


def test_bar_layout_and_preset(env: Path) -> None:
    assert run("bar", "layout", "left=workspaces", "center=", "right=clock,power") == 0
    cfg = config.load()
    assert cfg["bar"]["left"] == ["workspaces"]
    assert cfg["bar"]["center"] == []
    assert cfg["bar"]["right"] == ["clock", "power"]
    assert run("bar", "layout", "top=clock") == 1
    assert run("bar", "preset", "classic") == 0
    assert "taskbar" in config.load()["bar"]["left"]


def test_keys_bind_unbind(env: Path) -> None:
    assert run("keys", "bind", "Mod+F1", "exec", "foot", "-e", "htop") == 0
    assert config.load()["keys"]["bindings"]["Mod+F1"] == "exec foot -e htop"
    gen = (paths.generated_dir() / "sway" / "config").read_text()
    assert "bindsym --to-code Mod4+F1 exec foot -e htop" in gen
    assert run("keys", "bind", "Mod+F2", "exec", "a;", "b") == 1
    assert run("keys", "unbind", "Mod+F1") == 0
    assert "Mod4+F1" not in (paths.generated_dir() / "sway" / "config").read_text()


def test_set_generic(env: Path) -> None:
    assert run("set", "layout.gaps_inner", "14") == 0
    assert run("gaps", "4", "2") == 0
    cfg = config.load()
    assert (cfg["layout"]["gaps_inner"], cfg["layout"]["gaps_outer"]) == (4, 2)
    assert run("set", "layout.gaps_inner", "999") == 1


def test_wallpaper_set_and_reset(env: Path, tmp_path: Path) -> None:
    assert run("wallpaper", "set", str(tmp_path / "missing.png")) == 1
    img = tmp_path / "pic.png"
    img.write_bytes(b"\x89PNG\r\n\x1a\n")
    assert run("wallpaper", "set", str(img), "--mode", "center") == 0
    assert config.load()["wallpaper"]["path"] == str(img)
    assert run("wallpaper", "reset") == 0
    assert config.load()["wallpaper"]["path"] == ""


def test_reset_requires_yes_when_not_interactive(env: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    run("gaps", "20")
    monkeypatch.setattr("sys.stdin.isatty", lambda: False)
    assert run("reset") == 1
    assert run("reset", "--yes") == 0
    assert config.load()["layout"]["gaps_inner"] == 8
    assert run("backups", "restore", "latest") == 0
    assert config.load()["layout"]["gaps_inner"] == 20


def test_doctor_flags_broken_config(env: Path, capsys: pytest.CaptureFixture[str]) -> None:
    run("init", "-q")
    assert run("doctor") in (0, 1)  # programs may be missing; config must be fine
    assert "generated Sway config is valid" in capsys.readouterr().out
    paths.user_config().write_text('[layout]\ngaps_inner = "wide"\n')
    assert run("doctor") == 1
    assert "layout.gaps_inner" in capsys.readouterr().out


def test_explain_lists_help(env: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert run("explain", "bar") == 0
    out = capsys.readouterr().out
    assert "bar.position" in out and "theme.name" not in out


def test_generate_print(env: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert run("generate", "--print", "sway/config") == 0
    assert capsys.readouterr().out.startswith("# Generated by surfctl")
    assert run("generate", "--print", "nope") == 1


def test_cheatsheet_print(env: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert run("cheatsheet", "--print") == 0
    out = capsys.readouterr().out
    assert "Show this cheat sheet" in out and "Super + /" in out


def test_init_seeds_keyboard_from_installer(env: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr("surfd.system.system_keyboard", lambda: {"layout": "de", "variant": "nodeadkeys"})
    assert run("init", "-q") == 0
    cfg = config.load()
    assert (cfg["input"]["keyboard_layout"], cfg["input"]["keyboard_variant"]) == ("de", "nodeadkeys")
