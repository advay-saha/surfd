#!/usr/bin/env bash
# build.sh — build surfd: component RPMs, the live ISO, a netinstall ISO,
# or the experimental bootc container image.
#
# Run on a Fedora host (or a privileged Fedora container) whose release
# matches --releasever. ISO builds need root. See docs/build.md.
#
#   ./build.sh rpms                 build surfd RPMs into out/repo
#   sudo ./build.sh iso             rpms + live ISO (livemedia-creator)
#   ./build.sh netinstall --boot-iso Fedora-Everything-netinst.iso
#   ./build.sh container            bootc image (podman)
#   ./build.sh check                verify every kickstart package resolves
#   ./build.sh ks                   write the flattened kickstart to out/
#   ./build.sh --dry-run iso        print what would run
#
set -Eeuo pipefail

SURFD_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SURFD_VERSION="$(cat "${SURFD_ROOT}/VERSION")"

# ---- defaults (override with flags or environment) ----
RELEASEVER="${SURFD_RELEASEVER:-44}"
ARCH="$(uname -m)"
OUT_DIR="${SURFD_OUT:-${SURFD_ROOT}/out}"
SURFD_REPO_URL="${SURFD_REPO_URL:-}"      # use a hosted repo instead of local RPMs
BOOT_ISO=""
DRY_RUN=0
KEEP_BUILD=0
PERMISSIVE=0
SKIP_RPMS=0
ISO_LIMIT_MB=1536                          # 1.5 GiB budget from the project goals

usage() {
    sed -n '2,15p' "$0" | sed 's/^# \{0,1\}//'
    cat <<EOF

Options:
  --releasever N      Fedora release to base on (default: ${RELEASEVER})
  --out DIR           output directory (default: ${OUT_DIR})
  --repo-url URL      use a hosted surfd repo (e.g. Copr) instead of building RPMs
  --boot-iso PATH     Fedora netinstall ISO for the 'netinstall' command
  --selinux-permissive  temporarily set SELinux permissive during the ISO build
                        (livemedia-creator --no-virt requires it); restored after
  --skip-rpms         reuse the RPMs already in OUT/repo
  --keep-build        keep the temporary build directory
  --dry-run           print commands instead of running them
  -h, --help          this help
EOF
}

log()  { printf '\033[1;36m[surfd]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[surfd] warning:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[surfd] error:\033[0m %s\n' "$*" >&2; exit 1; }

run() {
    if (( DRY_RUN )); then
        printf '+ %q' "$1"; shift; printf ' %q' "$@"; printf '\n'
    else
        "$@"
    fi
}

need() {
    local cmd pkg
    for spec in "$@"; do
        cmd="${spec%%:*}"; pkg="${spec#*:}"
        command -v "$cmd" >/dev/null 2>&1 || die "missing '$cmd' (install with: sudo dnf install ${pkg})"
    done
}

require_fedora() {
    [[ -r /etc/os-release ]] || die "cannot read /etc/os-release"
    # shellcheck disable=SC1091
    . /etc/os-release
    if [[ "${ID:-}" != "fedora" && "${ID_LIKE:-}" != *fedora* ]]; then
        die "ISO builds must run on Fedora (found ${PRETTY_NAME:-unknown}). Use a Fedora VM or: podman run --privileged -v \$PWD:/src fedora:${RELEASEVER}"
    fi
    if [[ "${VERSION_ID:-}" != "${RELEASEVER}" ]]; then
        warn "host is Fedora ${VERSION_ID:-?} but target is ${RELEASEVER}; lorax templates should match the target release"
    fi
}

require_root() { (( DRY_RUN )) || [[ ${EUID} -eq 0 ]] || die "this step needs root (sudo ./build.sh $*)"; }

# ---------------------------------------------------------------- rpms ----
cmd_rpms() {
    if (( SKIP_RPMS )) && [[ -d "${OUT_DIR}/repo/repodata" ]]; then
        log "reusing RPMs in ${OUT_DIR}/repo (--skip-rpms)"
        return 0
    fi
    if [[ -n "${SURFD_REPO_URL}" ]]; then
        log "using hosted surfd repo ${SURFD_REPO_URL}; skipping local RPM build"
        return 0
    fi
    need rpmbuild:rpm-build createrepo_c:createrepo_c
    run "${SURFD_ROOT}/packaging/build-rpms.sh" --out "${OUT_DIR}/repo"
    run createrepo_c --quiet "${OUT_DIR}/repo"
    log "surfd RPM repository ready in ${OUT_DIR}/repo"
}

# ----------------------------------------------------- kickstart assembly ----
flatten_ks() {
    local dest="$1" repo_line
    need ksflatten:pykickstart
    local entry="surfd-${ARCH}.ks"
    [[ -f "${SURFD_ROOT}/kickstarts/${entry}" ]] || die "unsupported architecture ${ARCH} (have: x86_64, aarch64)"

    if [[ -n "${SURFD_REPO_URL}" ]]; then
        repo_line="repo --name=surfd --baseurl=${SURFD_REPO_URL}"
    else
        repo_line="repo --name=surfd-local --baseurl=file://${OUT_DIR}/repo"
    fi

    log "flattening kickstarts/${entry} for Fedora ${RELEASEVER}"
    if (( DRY_RUN )); then
        printf '+ (cd kickstarts && ksflatten -v F%s -c %s) > %s\n' "${RELEASEVER}" "${entry}" "${dest}"
        return 0
    fi
    (
        cd "${SURFD_ROOT}/kickstarts"
        {
            printf '# Generated by build.sh on %s — do not edit\n' "$(date -u +%FT%TZ)"
            printf '%s\n' "${repo_line}"
            ksflatten -v "F${RELEASEVER}" -c "${entry}"
        } > "${dest}"
    )
    ksvalidator -v "F${RELEASEVER}" "${dest}" >/dev/null || die "flattened kickstart failed validation: ${dest}"
}

# --------------------------------------------------------------- check ----
cmd_check() {
    local tmp
    tmp="$(mktemp -d)"
    trap 'rm -rf "${tmp}"' RETURN
    flatten_ks "${tmp}/surfd.ks"
    (( DRY_RUN )) && return 0
    run "${SURFD_ROOT}/tools/check-packages.sh" --releasever "${RELEASEVER}" --arch "${ARCH}" \
        --surfd-repo "${SURFD_REPO_URL:-file://${OUT_DIR}/repo}" "${tmp}/surfd.ks"
}

# ------------------------------------------------------------------ ks ----
cmd_ks() {
    mkdir -p "${OUT_DIR}"
    flatten_ks "${OUT_DIR}/surfd-${ARCH}-flat.ks"
    log "wrote ${OUT_DIR}/surfd-${ARCH}-flat.ks"
}

# ----------------------------------------------------------------- iso ----
selinux_restore=""
restore_selinux() {
    if [[ -n "${selinux_restore}" ]]; then
        log "restoring SELinux to ${selinux_restore}"
        setenforce "${selinux_restore}" || warn "could not restore SELinux mode"
    fi
}

cmd_iso() {
    require_root iso
    require_fedora
    need livemedia-creator:lorax-lmc-novirt ksflatten:pykickstart anaconda:anaconda-tui
    cmd_rpms

    local build iso_name volid
    build="$(mktemp -d /var/tmp/surfd-build.XXXXXX)"
    iso_name="surfd-${SURFD_VERSION}-f${RELEASEVER}-${ARCH}.iso"
    # ISO9660 volume IDs are limited to 32 characters
    volid="surfd-${SURFD_VERSION}-${ARCH}"
    volid="${volid:0:32}"

    if command -v getenforce >/dev/null && [[ "$(getenforce)" == "Enforcing" ]]; then
        if (( PERMISSIVE )); then
            selinux_restore=1
            trap restore_selinux EXIT
            run setenforce 0
        else
            die "SELinux is enforcing on the build host; livemedia-creator --no-virt needs permissive. Re-run with --selinux-permissive (it is restored afterwards). The resulting image is still SELinux-enforcing."
        fi
    fi

    flatten_ks "${build}/surfd.ks"
    mkdir -p "${OUT_DIR}/iso"
    log "building ${iso_name} (this takes 20-60 minutes)"
    run livemedia-creator \
        --ks "${build}/surfd.ks" \
        --no-virt \
        --make-iso \
        --iso-only \
        --iso-name "${iso_name}" \
        --project surfd \
        --releasever "${RELEASEVER}" \
        --volid "${volid}" \
        --title "surfd ${SURFD_VERSION}" \
        --resultdir "${build}/result" \
        --logfile "${OUT_DIR}/iso/livemedia-creator.log" \
        --tmp /var/tmp

    (( DRY_RUN )) && return 0
    mv "${build}/result/${iso_name}" "${OUT_DIR}/iso/"
    finish_iso "${OUT_DIR}/iso/${iso_name}"
    (( KEEP_BUILD )) || rm -rf "${build}"
}

finish_iso() {
    local iso="$1" size_mb
    size_mb=$(( $(stat -c %s "${iso}") / 1024 / 1024 ))
    ( cd "$(dirname "${iso}")" && sha256sum "$(basename "${iso}")" > "$(basename "${iso}").sha256" )
    log "ISO: ${iso} (${size_mb} MiB)"
    log "SHA256: $(cut -d' ' -f1 "${iso}.sha256")"
    if (( size_mb > ISO_LIMIT_MB )); then
        warn "ISO is ${size_mb} MiB, over the ${ISO_LIMIT_MB} MiB budget. Run: tools/iso-size-report.sh ${iso}"
    fi
}

# ----------------------------------------------------------- netinstall ----
# Embeds the installable kickstart into a stock Fedora netinstall ISO with
# mkksiso. Packages are fetched at install time, so the surfd repo must be
# reachable over the network (--repo-url, e.g. Copr).
cmd_netinstall() {
    need mkksiso:lorax ksflatten:pykickstart
    [[ -n "${BOOT_ISO}" ]] || die "netinstall needs --boot-iso Fedora-Everything-netinst-${ARCH}-${RELEASEVER}-*.iso"
    [[ -n "${SURFD_REPO_URL}" ]] || die "netinstall needs --repo-url (a network-reachable surfd repo, e.g. Copr)"
    local build out
    build="$(mktemp -d)"
    out="${OUT_DIR}/iso/surfd-${SURFD_VERSION}-f${RELEASEVER}-${ARCH}-netinstall.iso"
    mkdir -p "${OUT_DIR}/iso"
    (( DRY_RUN )) || {
        # Same composition as the live image minus surfd-live.ks: no live
        # disk layout, so Anaconda asks for the target disk interactively
        # and installs a real bootloader.
        printf '%%include %s\n' surfd-repos.ks surfd-base.ks surfd-desktop.ks \
            "surfd-boot-${ARCH}.ks" > "${SURFD_ROOT}/kickstarts/.surfd-install-${ARCH}.ks"
        (
            cd "${SURFD_ROOT}/kickstarts"
            printf 'repo --name=surfd --baseurl=%s --install\n' "${SURFD_REPO_URL}"
            ksflatten -v "F${RELEASEVER}" -c ".surfd-install-${ARCH}.ks"
        ) > "${build}/surfd-install.ks"
        rm -f "${SURFD_ROOT}/kickstarts/.surfd-install-${ARCH}.ks"
        ksvalidator -v "F${RELEASEVER}" "${build}/surfd-install.ks" >/dev/null
    }
    run mkksiso --ks "${build}/surfd-install.ks" "${BOOT_ISO}" "${out}"
    (( DRY_RUN )) || finish_iso "${out}"
}

# ------------------------------------------------------------ container ----
cmd_container() {
    need podman:podman
    run podman build \
        --build-arg "FEDORA_VERSION=${RELEASEVER}" \
        -f "${SURFD_ROOT}/containers/Containerfile" \
        -t "localhost/surfd-bootc:${RELEASEVER}" \
        "${SURFD_ROOT}"
    log "image: localhost/surfd-bootc:${RELEASEVER} (experimental; see containers/README.md)"
}

# ---------------------------------------------------------------- main ----
COMMAND=""
while (( $# )); do
    case "$1" in
        --releasever)        RELEASEVER="${2:?}"; shift 2 ;;
        --out)               OUT_DIR="$(realpath -m "${2:?}")"; shift 2 ;;
        --repo-url)          SURFD_REPO_URL="${2:?}"; shift 2 ;;
        --boot-iso)          BOOT_ISO="$(realpath "${2:?}")"; shift 2 ;;
        --selinux-permissive) PERMISSIVE=1; shift ;;
        --keep-build)        KEEP_BUILD=1; shift ;;
        --skip-rpms)         SKIP_RPMS=1; shift ;;
        --dry-run)           DRY_RUN=1; shift ;;
        -h|--help)           usage; exit 0 ;;
        rpms|iso|netinstall|container|check|ks) COMMAND="$1"; shift ;;
        *) usage >&2; die "unknown argument: $1" ;;
    esac
done

[[ "${RELEASEVER}" =~ ^[0-9]+$ ]] || die "--releasever must be a number"
[[ -n "${COMMAND}" ]] || { usage; exit 1; }

log "surfd ${SURFD_VERSION} · Fedora ${RELEASEVER} · ${ARCH} · ${COMMAND}$( (( DRY_RUN )) && echo ' (dry run)')"
"cmd_${COMMAND}"
