#!/usr/bin/env python3
"""Generate surfd's original SVG artwork (deterministic; committed to git).

    python3 theme/tools/make_art.py      # rewrites the SVG sources

Outputs:
  theme/logos/surfd-mark.svg        the wave mark
  theme/logos/surfd-wordmark.svg    monoline "surfd" lettering (paths, no fonts)
  theme/logos/surfd-logo.svg        mark + wordmark, horizontal
  theme/themes/*/wallpapers/*.svg   one wallpaper per theme and variant

All artwork: CC-BY-SA-4.0, surfd contributors. No third-party material.
"""

from __future__ import annotations

import math
import random
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
W, H = 3840, 2160
LICENSE_NOTE = "<!-- surfd artwork · CC-BY-SA-4.0 · surfd contributors · generated by theme/tools/make_art.py -->"


def svg(width: int, height: int, body: str, view: str | None = None) -> str:
    vb = view or f"0 0 {width} {height}"
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n{LICENSE_NOTE}\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="{vb}">\n{body}\n</svg>\n')


def mix(a: str, b: str, t: float) -> str:
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(pa, pb, strict=True))


def smooth_path(points: list[tuple[float, float]], close_to: float | None = None) -> str:
    """Catmull-Rom spline through points, as cubic Béziers; optionally closed down to y=close_to."""
    d = f"M{points[0][0]:.1f},{points[0][1]:.1f}"
    for i in range(len(points) - 1):
        p0 = points[max(i - 1, 0)]
        p1, p2 = points[i], points[i + 1]
        p3 = points[min(i + 2, len(points) - 1)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f" C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}"
    if close_to is not None:
        d += f" L{points[-1][0]:.1f},{close_to} L{points[0][0]:.1f},{close_to} Z"
    return d


