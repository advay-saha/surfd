#!/usr/bin/env python3
"""Generate surfd's original SVG artwork (deterministic; committed to git).

    python3 theme/tools/make_art.py      # rewrites the SVG sources

Outputs:
  theme/logos/surfd-mark*.svg       the S mark, one colour (-dark: for light backgrounds)
  theme/logos/surfd-wordmark*.svg   the "surfd" lettering (outlines, no fonts needed)
  theme/logos/surfd-logo*.svg       mark + wordmark, horizontal
  src/*/data/org.surfd.*.svg        app icons (Settings, Welcome, Installer)
  theme/themes/*/wallpapers/*.svg   one wallpaper per theme and variant

The S and the lettering come from brand_paths.py (see docs/brand.md).

All artwork: CC-BY-SA-4.0, surfd contributors. No third-party material.
"""

from __future__ import annotations

import math
import random
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from brand_paths import S_PATH, S_SIZE, WORD_BOX, WORD_PATH

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parent
W, H = 3840, 2160
LICENSE_NOTE = "<!-- surfd artwork · CC-BY-SA-4.0 · surfd contributors · generated by theme/tools/make_art.py -->"


def svg(width: int, height: int, body: str, view: str | None = None) -> str:
    vb = view or f"0 0 {width} {height}"
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n{LICENSE_NOTE}\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="{vb}">\n{body}\n</svg>\n')


def mix(a: str, b: str, t: float) -> str:
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(pa, pb, strict=True))


def smooth_path(points: list[tuple[float, float]], close_to: float | None = None) -> str:
    """Catmull-Rom spline through points, as cubic Béziers; optionally closed down to y=close_to."""
    d = f"M{points[0][0]:.1f},{points[0][1]:.1f}"
    for i in range(len(points) - 1):
        p0 = points[max(i - 1, 0)]
        p1, p2 = points[i], points[i + 1]
        p3 = points[min(i + 2, len(points) - 1)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f" C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}"
    if close_to is not None:
        d += f" L{points[-1][0]:.1f},{close_to} L{points[0][0]:.1f},{close_to} Z"
    return d


# ------------------------------------------------------------------ logos --

# The brand palette (the banner's colours). Tide's theme.toml uses the same values.
NAVY = "#0c1b23"       # background
MIST = "#dee9ef"       # text on dark
TEAL = "#5ecfc2"       # the logo colour, accent on dark
BLUE = "#4a90c8"       # second accent: gradients and icon tiles
TEAL_DEEP = "#0f8f85"  # the logo colour on light backgrounds
INK = "#15262f"        # text on light

S_ASPECT = S_SIZE[0] / S_SIZE[1]                       # ~1.7: a wide, heavy S
WORD_W, WORD_H = WORD_BOX[2] - WORD_BOX[0], WORD_BOX[3] - WORD_BOX[1]   # font units, y-down


def s_shape(x: float, y: float, width: float, fill: str) -> str:
    """The S, `width` wide with its top-left at (x, y)."""
    k = width / S_SIZE[0]
    return f'<path transform="translate({x:.2f},{y:.2f}) scale({k:.5f})" d="{S_PATH}" fill="{fill}"/>'


def word_shape(x: float, y: float, height: float, fill: str) -> tuple[str, float]:
    """The lettering, ascender-to-baseline `height` tall, top-left at (x, y). Returns (svg, width)."""
    k = height / WORD_H
    t = f"translate({x - WORD_BOX[0] * k:.2f},{y - WORD_BOX[1] * k:.2f}) scale({k:.5f})"
    return f'<path transform="{t}" d="{WORD_PATH}" fill="{fill}"/>', WORD_W * k


def mark_svg(size: int = 128, fill: str = TEAL) -> str:
    """The S alone, centred in a square canvas on a transparent background."""
    w = size * 0.94
    h = w / S_ASPECT
    return svg(size, size, s_shape((size - w) / 2, (size - h) / 2, w, fill), f"0 0 {size} {size}")


def wordmark_svg(color: str = MIST) -> str:
    pad = 4
    body, width = word_shape(pad, pad, 64, color)
    return svg(round(width + 2 * pad), 64 + 2 * pad, body, f"0 0 {round(width + 2 * pad)} {64 + 2 * pad}")


def logo_svg(text: str = MIST, mark: str = TEAL) -> str:
    """Horizontal lock-up: S, then the lettering; the S sits on the lettering's baseline at x-height."""
    pad, h = 6, 64
    s_h = h * 0.69                       # a touch above the lettering's x-height, so the S reads as a capital
    s_w = s_h * S_ASPECT
    parts = [s_shape(pad, pad + h - s_h, s_w, mark)]
    word, width = word_shape(pad + s_w + h * 0.2, pad, h, text)
    parts.append(word)
    total = round(pad * 2 + s_w + h * 0.2 + width)
    return svg(total, h + 2 * pad, "\n".join(parts), f"0 0 {total} {h + 2 * pad}")


# ------------------------------------------------------------------- icons --

def tile(glyph: str, gid: str = "g") -> str:
    """A rounded app-icon tile (teal to blue) with a navy glyph on top."""
    return f"""<defs>
  <linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="{TEAL}"/><stop offset="1" stop-color="{BLUE}"/>
  </linearGradient>
</defs>
<rect x="8" y="12" width="112" height="104" rx="26" fill="{NAVY}"/>
<rect x="8" y="8" width="112" height="104" rx="26" fill="url(#{gid})"/>
{glyph}"""


def icon_welcome() -> str:
    w = 84
    return svg(128, 128, tile(s_shape((128 - w) / 2, 60 - w / S_ASPECT / 2, w, NAVY)), "0 0 128 128")


def icon_installer() -> str:
    w = 64
    glyph = (s_shape((128 - w) / 2, 22, w, NAVY) +
             f'\n<path d="M64,72 V92 M52,82 L64,94 L76,82" fill="none" stroke="{NAVY}" stroke-width="8" '
             'stroke-linecap="round" stroke-linejoin="round"/>')
    return svg(128, 128, tile(glyph), "0 0 128 128")


def icon_settings() -> str:
    glyph = f"""<g stroke="{NAVY}" stroke-width="8" stroke-linecap="round">
    <path d="M30,36 H98"/><path d="M30,60 H98"/><path d="M30,84 H98"/>
  </g>
  <g fill="#ffffff" stroke="{NAVY}" stroke-width="5">
    <circle cx="48" cy="36" r="10"/><circle cx="82" cy="60" r="10"/><circle cx="58" cy="84" r="10"/>
  </g>"""
    return svg(128, 128, tile(glyph), "0 0 128 128")


# ------------------------------------------------------------- wallpapers --

def load_palette(theme: str, variant: str) -> dict[str, str]:
    with (ROOT / "themes" / theme / "theme.toml").open("rb") as fh:
        return tomllib.load(fh)[variant]


def grain_filter() -> str:
    # Very subtle grain to prevent gradient banding on 8-bit displays.
    return """<filter id="grain" x="0" y="0" width="100%" height="100%">
  <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="2" seed="7" result="n"/>
  <feColorMatrix in="n" type="matrix" values="0 0 0 0 0.5  0 0 0 0 0.5  0 0 0 0 0.5  0 0 0 0.05 0" result="g"/>
  <feComposite in="g" in2="SourceGraphic" operator="over"/>
</filter>"""


def tide(p: dict[str, str], dark: bool) -> str:
    rng = random.Random(42)
    if dark:
        sky_top = mix(p["background"], "#000000", 0.35)
        sky_bot = mix(p["background"], p.get("accent2", p["accent"]), 0.34)
    else:
        sky_top = mix(p["background"], p["accent"], 0.18)
        sky_bot = mix(p["background"], "#ffffff", 0.6)
    horizon = H * 0.56
    layers = []
    n = 8
    for i in range(n):
        t = i / (n - 1)
        base = horizon + (H - horizon) * (t ** 1.35) * 0.92
        amp = 14 + 46 * t
        wl = W / (2.2 + 1.2 * rng.random())
        phase = rng.random() * math.tau
        pts = [(x, base + amp * math.sin(x / wl * math.tau + phase) + 0.3 * amp * math.sin(x / wl * 2.7 * math.tau + i))
               for x in range(-200, W + 201, 120)]
        if dark:
            # far swells lean blue, near swells teal: the logo's gradient, laid out as sea
            hue = mix(p.get("accent2", p["accent"]), p["accent"], t)
            fill = mix(mix(hue, p["background"], 0.5), mix(p["background"], "#000000", 0.2), t)
            crest = mix(hue, "#ffffff", 0.3)
        else:
            fill = mix(mix(p["accent"], "#ffffff", 0.55), p["accent"], 0.15 + 0.7 * t)
            crest = "#ffffff"
        layers.append(f'<path d="{smooth_path(pts, H + 10)}" fill="{fill}"/>')
        layers.append(f'<path d="{smooth_path([(x, y - 1) for x, y in pts])}" fill="none" stroke="{crest}" '
                      f'stroke-opacity="{0.22 + 0.2 * (1 - t):.2f}" stroke-width="{2 + 3 * t:.1f}"/>')
    orb_x, orb_y, orb_r = W * 0.68, H * 0.36, H * 0.075
    orb = mix(p["accent"], "#ffffff", 0.3) if dark else "#ffffff"
    # moonlight / sunlight path on the water: short horizontal glints
    glints = []
    for k in range(34):
        y = horizon + 30 + k * k * 1.15
        if y > H:
            break
        half = (60 + k * 9) * (0.6 + 0.4 * rng.random())
        cx = orb_x + rng.uniform(-20, 20) * (1 + k / 6)
        glints.append(f'<rect x="{cx - half:.0f}" y="{y:.0f}" width="{2 * half:.0f}" height="{4 + k * 0.35:.1f}" '
                      f'rx="3" fill="{orb}" fill-opacity="{max(0.04, 0.32 - k * 0.009):.2f}"/>')
    body = f"""<defs>
  <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{sky_top}"/><stop offset="0.56" stop-color="{sky_bot}"/>
  </linearGradient>
  <radialGradient id="glow" cx="{orb_x / W:.3f}" cy="{orb_y / H:.3f}" r="0.42" gradientTransform="translate({orb_x / W:.3f} {orb_y / H:.3f}) scale(1 1.78) translate(-{orb_x / W:.3f} -{orb_y / H:.3f})">
    <stop offset="0" stop-color="{orb}" stop-opacity="{0.36 if dark else 0.55}"/>
    <stop offset="1" stop-color="{orb}" stop-opacity="0"/>
  </radialGradient>
  {grain_filter()}
</defs>
<g filter="url(#grain)">
<rect width="{W}" height="{H}" fill="url(#sky)"/>
<rect width="{W}" height="{H}" fill="url(#glow)"/>
<circle cx="{orb_x:.0f}" cy="{orb_y:.0f}" r="{orb_r:.0f}" fill="{orb}" fill-opacity="{0.92 if dark else 0.9}"/>
{chr(10).join(layers)}
{chr(10).join(glints)}
</g>"""
    return svg(W, H, body)


def driftwood(p: dict[str, str], dark: bool) -> str:
    rng = random.Random(7)
    top = mix(p["background"], p["accent"], 0.10 if dark else 0.08)
    horizon = mix(p["accent"], p["background"], 0.55)
    dunes = []
    n = 5
    for i in range(n):
        t = i / (n - 1)
        base = H * (0.56 + 0.1 * i)
        pts = []
        for k in range(9):
            x = -300 + k * (W + 600) / 8
            pts.append((x, base - (180 + 120 * rng.random()) * math.sin((k + rng.random()) * 0.9) * (1 - 0.4 * t)))
        if dark:
            light = mix(p["accent"], p["surface_alt"], 0.3 + 0.2 * t)
            shade = mix(light, p["background"], 0.45 + 0.35 * t)
        else:
            light = mix(p["accent"], p["background"], 0.62 - 0.38 * t)
            shade = mix(light, p["text"], 0.1 + 0.12 * t)
        gid = f"d{i}"
        dunes.append(f'<linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="0.4">'
                     f'<stop offset="0" stop-color="{light}"/><stop offset="1" stop-color="{shade}"/></linearGradient>')
        dunes.append(f'<path d="{smooth_path(pts, H + 10)}" fill="url(#{gid})"/>')
    sun = mix(p["accent"], "#ffffff", 0.25 if dark else 0.7)
    body = f"""<defs>
  <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{top}"/><stop offset="0.6" stop-color="{horizon}"/>
  </linearGradient>
  {grain_filter()}
</defs>
<g filter="url(#grain)">
<rect width="{W}" height="{H}" fill="url(#sky)"/>
<circle cx="{W * 0.3:.0f}" cy="{H * 0.47:.0f}" r="{H * 0.13:.0f}" fill="{sun}" fill-opacity="{0.8 if dark else 0.7}"/>
{chr(10).join(dunes)}
</g>"""
    return svg(W, H, body)


def ribbon(center: list[tuple[float, float]], width: float) -> str:
    """A tapered ribbon around a centre line (wide at the base, pointed at the tip)."""
    left, right = [], []
    n = len(center)
    for i, (x, y) in enumerate(center):
        a = center[max(i - 1, 0)]
        b = center[min(i + 1, n - 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        length = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / length, dx / length
        w = width * (1 - i / (n - 1)) ** 0.8 + 2
        left.append((x + nx * w, y + ny * w))
        right.append((x - nx * w, y - ny * w))
    outline = left + right[::-1]
    return smooth_path(outline) + " Z"


def kelp(p: dict[str, str], dark: bool) -> str:
    rng = random.Random(11)
    top = mix(p["background"], p["accent"], 0.22 if dark else 0.28)
    bottom = mix(p["background"], "#000000", 0.45) if dark else mix(p["background"], p["accent"], 0.08)
    layers: dict[int, list[str]] = {0: [], 1: [], 2: []}
    for layer, count in ((0, 22), (1, 14), (2, 8)):
        for i in range(count):
            x0 = rng.uniform(-150, W + 150)
            height = H * rng.uniform(0.45, 0.95) * (0.8 + 0.12 * layer)
            sway = rng.uniform(80, 260)
            ph = rng.random() * math.tau
            pts = [(x0 + sway * math.sin(k / 4.5 + ph) * (k / 14) + 8 * math.sin(k * 0.9 + i),
                    H + 60 - height * k / 14) for k in range(15)]
            width = (20, 34, 52)[layer] * rng.uniform(0.7, 1.2)
            if dark:
                col = mix(p["accent"], p["background"], (0.72, 0.5, 0.25)[layer])
            else:
                col = mix(p["accent"], p["background"], (0.75, 0.5, 0.2)[layer])
            layers[layer].append(f'<path d="{ribbon(pts, width)}" fill="{col}"/>')
    rays = []
    for k in range(6):
        x = W * (0.15 + 0.14 * k) + rng.uniform(-80, 80)
        spread = rng.uniform(160, 360)
        rays.append(f'<polygon points="{x - 40:.0f},0 {x + 40:.0f},0 {x + spread:.0f},{H} {x - spread * 0.4:.0f},{H}" '
                    f'fill="{p["text"] if dark else "#ffffff"}" fill-opacity="{rng.uniform(0.025, 0.06):.3f}"/>')
    bubbles = []
    for _ in range(36):
        r = rng.uniform(5, 18)
        bubbles.append(f'<circle cx="{rng.uniform(0, W):.0f}" cy="{rng.uniform(0, H * 0.8):.0f}" r="{r:.1f}" '
                       f'fill="none" stroke="{p["text"] if dark else "#ffffff"}" '
                       f'stroke-opacity="{rng.uniform(0.12, 0.3):.2f}" stroke-width="3"/>')
    body = f"""<defs>
  <linearGradient id="sea" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{top}"/><stop offset="1" stop-color="{bottom}"/>
  </linearGradient>
  <filter id="far" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="10"/></filter>
  <filter id="mid" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="3"/></filter>
  {grain_filter()}
</defs>
<g filter="url(#grain)">
<rect width="{W}" height="{H}" fill="url(#sea)"/>
{chr(10).join(rays)}
<g filter="url(#far)">{"".join(layers[0])}</g>
<g filter="url(#mid)">{"".join(layers[1])}</g>
{"".join(layers[2])}
{chr(10).join(bubbles)}
</g>"""
    return svg(W, H, body)


def main() -> None:
    logos = ROOT / "logos"
    logos.mkdir(exist_ok=True)
    (logos / "surfd-mark.svg").write_text(mark_svg())
    (logos / "surfd-mark-dark.svg").write_text(mark_svg(fill=TEAL_DEEP))
    (logos / "surfd-wordmark.svg").write_text(wordmark_svg())
    (logos / "surfd-wordmark-dark.svg").write_text(wordmark_svg(INK))
    (logos / "surfd-logo.svg").write_text(logo_svg())
    (logos / "surfd-logo-dark.svg").write_text(logo_svg(INK, TEAL_DEEP))
    (REPO / "src/settings/data/org.surfd.Welcome.svg").write_text(icon_welcome())
    (REPO / "src/settings/data/org.surfd.Settings.svg").write_text(icon_settings())
    (REPO / "src/installer/data/org.surfd.Installer.svg").write_text(icon_installer())
    for name, fn in (("tide", tide), ("driftwood", driftwood), ("kelp", kelp)):
        for variant in ("dark", "light"):
            out = ROOT / "themes" / name / "wallpapers" / f"{name}-{variant}.svg"
            out.write_text(fn(load_palette(name, variant), variant == "dark"))
    print("artwork written")


if __name__ == "__main__":
    main()
