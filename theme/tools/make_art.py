def mark_body(bg: str = "#5fd3c4", fg: str = "#0d1b24", bg2: str = "#2a8fb8") -> str:
    return f"""<defs>
  <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0" stop-color="{bg}"/><stop offset="1" stop-color="{bg2}"/>
  </linearGradient>
</defs>
<circle cx="64" cy="64" r="60" fill="url(#g)"/>
<path d="{MARK_PATH}" fill="none" stroke="{fg}" stroke-width="10" stroke-linecap="round" stroke-linejoin="round"/>
<path d="M22,98 C40,92 52,96 64,98 C78,100 90,96 106,92" fill="none" stroke="{fg}" stroke-opacity="0.45"
      stroke-width="7" stroke-linecap="round"/>"""


def mark_svg(size: int = 128) -> str:
    return svg(size, size, mark_body(), "0 0 128 128")


# Monoline lowercase letters on a 0..40 x-height grid (baseline y=40),
# drawn as strokes so no font is needed to render the logo.
LETTERS = {
    "s": ("M30,8 C26,1 14,-1 7,3 C0,8 2,17 11,19 L21,21 C30,23 32,32 26,37 C19,42 6,41 2,33", 32),
    "u": ("M2,0 V22 C2,33 9,40 19,40 C29,40 36,33 36,22 V0 M36,22 V40", 38),
    "r": ("M2,40 V0 M2,18 C2,7 10,0 22,0 C25,0 27,0.5 29,1.5", 30),
    "f": ("M28,-17 C25,-19 22,-20 18,-20 C10,-20 6,-14 6,-6 V40 M-2,2 H22", 29),
    "d": ("M36,-22 V40 M36,20 C36,31 28,40 19,40 C9,40 2,31 2,20 C2,9 9,0 19,0 C28,0 36,9 36,20", 38),
}


def wordmark_body(color: str, x0: float = 0, y0: float = 0, scale: float = 1.0, stroke: float = 6.5) -> tuple[str, float]:
    parts, x = [], 0.0
    for ch in "surfd":
        d, adv = LETTERS[ch]
        parts.append(f'<path transform="translate({x:.1f},0)" d="{d}"/>')
        x += adv + 9
    width = x - 9
    g = (f'<g transform="translate({x0},{y0}) scale({scale})" fill="none" stroke="{color}" '
         f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{"".join(parts)}</g>')
    return g, width * scale


def wordmark_svg(color: str = "#dfeaef") -> str:
    g, width = wordmark_body(color, 4, 26)
    return svg(round(width + 8), 72, g, f"0 0 {round(width + 8)} 72")


def logo_svg(text: str = "#dfeaef") -> str:
    mark = mark_body()
    g, width = wordmark_body(text, 150, 46, 1.6, 6.5)
    total = round(150 + width + 12)
    return svg(total, 128, f'<g>{mark}</g>\n{g}', f"0 0 {total} 128")


# ------------------------------------------------------------- wallpapers --

def load_palette(theme: str, variant: str) -> dict[str, str]:
    with (ROOT / "themes" / theme / "theme.toml").open("rb") as fh:
        return tomllib.load(fh)[variant]


def grain_filter() -> str:
    # Very subtle grain to prevent gradient banding on 8-bit displays.
    return """<filter id="grain" x="0" y="0" width="100%" height="100%">
  <feTurbulence type="fractalNoise" baseFrequency="0.9" numOctaves="2" seed="7" result="n"/>
  <feColorMatrix in="n" type="matrix" values="0 0 0 0 0.5  0 0 0 0 0.5  0 0 0 0 0.5  0 0 0 0.05 0" result="g"/>
  <feComposite in="g" in2="SourceGraphic" operator="over"/>
</filter>"""


def tide(p: dict[str, str], dark: bool) -> str:
    rng = random.Random(42)
    if dark:
        sky_top = mix(p["background"], "#000000", 0.35)
        sky_bot = mix(p["background"], p["accent"], 0.22)
    else:
        sky_top = mix(p["background"], p["accent"], 0.18)
        sky_bot = mix(p["background"], "#ffffff", 0.6)
    horizon = H * 0.56
    layers = []
    n = 8
    for i in range(n):
        t = i / (n - 1)
        base = horizon + (H - horizon) * (t ** 1.35) * 0.92
        amp = 14 + 46 * t
        wl = W / (2.2 + 1.2 * rng.random())
        phase = rng.random() * math.tau
        pts = [(x, base + amp * math.sin(x / wl * math.tau + phase) + 0.3 * amp * math.sin(x / wl * 2.7 * math.tau + i))
               for x in range(-200, W + 201, 120)]
        if dark:
            fill = mix(mix(p["accent"], p["background"], 0.62), mix(p["background"], "#000000", 0.25), t)
            crest = mix(p["accent"], "#ffffff", 0.3)
        else:
            fill = mix(mix(p["accent"], "#ffffff", 0.55), p["accent"], 0.15 + 0.7 * t)
            crest = "#ffffff"
        layers.append(f'<path d="{smooth_path(pts, H + 10)}" fill="{fill}"/>')
        layers.append(f'<path d="{smooth_path([(x, y - 1) for x, y in pts])}" fill="none" stroke="{crest}" '
                      f'stroke-opacity="{0.22 + 0.2 * (1 - t):.2f}" stroke-width="{2 + 3 * t:.1f}"/>')
    orb_x, orb_y, orb_r = W * 0.68, H * 0.36, H * 0.075
    orb = mix(p["accent"], "#ffffff", 0.45) if dark else "#ffffff"
    # moonlight / sunlight path on the water: short horizontal glints
    glints = []
    for k in range(34):
        y = horizon + 30 + k * k * 1.15
        if y > H:
            break
        half = (60 + k * 9) * (0.6 + 0.4 * rng.random())
        cx = orb_x + rng.uniform(-20, 20) * (1 + k / 6)
        glints.append(f'<rect x="{cx - half:.0f}" y="{y:.0f}" width="{2 * half:.0f}" height="{4 + k * 0.35:.1f}" '
                      f'rx="3" fill="{orb}" fill-opacity="{max(0.04, 0.32 - k * 0.009):.2f}"/>')
    body = f"""<defs>
  <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{sky_top}"/><stop offset="0.56" stop-color="{sky_bot}"/>
  </linearGradient>
  <radialGradient id="glow" cx="{orb_x / W:.3f}" cy="{orb_y / H:.3f}" r="0.42" gradientTransform="translate({orb_x / W:.3f} {orb_y / H:.3f}) scale(1 1.78) translate(-{orb_x / W:.3f} -{orb_y / H:.3f})">
    <stop offset="0" stop-color="{orb}" stop-opacity="{0.30 if dark else 0.55}"/>
    <stop offset="1" stop-color="{orb}" stop-opacity="0"/>
  </radialGradient>
  {grain_filter()}
</defs>
<g filter="url(#grain)">
<rect width="{W}" height="{H}" fill="url(#sky)"/>
<rect width="{W}" height="{H}" fill="url(#glow)"/>
<circle cx="{orb_x:.0f}" cy="{orb_y:.0f}" r="{orb_r:.0f}" fill="{orb}" fill-opacity="{0.92 if dark else 0.9}"/>
{chr(10).join(layers)}
{chr(10).join(glints)}
</g>"""
    return svg(W, H, body)


def driftwood(p: dict[str, str], dark: bool) -> str:
    rng = random.Random(7)
    top = mix(p["background"], p["accent"], 0.10 if dark else 0.08)
    horizon = mix(p["accent"], p["background"], 0.55)
    dunes = []
    n = 5
    for i in range(n):
        t = i / (n - 1)
        base = H * (0.56 + 0.1 * i)
        pts = []
        for k in range(9):
            x = -300 + k * (W + 600) / 8
            pts.append((x, base - (180 + 120 * rng.random()) * math.sin((k + rng.random()) * 0.9) * (1 - 0.4 * t)))
        if dark:
            light = mix(p["accent"], p["surface_alt"], 0.3 + 0.2 * t)
            shade = mix(light, p["background"], 0.45 + 0.35 * t)
        else:
            light = mix(p["accent"], p["background"], 0.62 - 0.38 * t)
            shade = mix(light, p["text"], 0.1 + 0.12 * t)
        gid = f"d{i}"
        dunes.append(f'<linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="0.4">'
                     f'<stop offset="0" stop-color="{light}"/><stop offset="1" stop-color="{shade}"/></linearGradient>')
        dunes.append(f'<path d="{smooth_path(pts, H + 10)}" fill="url(#{gid})"/>')
    sun = mix(p["accent"], "#ffffff", 0.25 if dark else 0.7)
    body = f"""<defs>
  <linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{top}"/><stop offset="0.6" stop-color="{horizon}"/>
  </linearGradient>
  {grain_filter()}
</defs>
<g filter="url(#grain)">
<rect width="{W}" height="{H}" fill="url(#sky)"/>
<circle cx="{W * 0.3:.0f}" cy="{H * 0.47:.0f}" r="{H * 0.13:.0f}" fill="{sun}" fill-opacity="{0.8 if dark else 0.7}"/>
{chr(10).join(dunes)}
</g>"""
    return svg(W, H, body)


def ribbon(center: list[tuple[float, float]], width: float) -> str:
    """A tapered ribbon around a centre line (wide at the base, pointed at the tip)."""
    left, right = [], []
    n = len(center)
    for i, (x, y) in enumerate(center):
        a = center[max(i - 1, 0)]
        b = center[min(i + 1, n - 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        length = math.hypot(dx, dy) or 1.0
        nx, ny = -dy / length, dx / length
        w = width * (1 - i / (n - 1)) ** 0.8 + 2
        left.append((x + nx * w, y + ny * w))
        right.append((x - nx * w, y - ny * w))
    outline = left + right[::-1]
    return smooth_path(outline) + " Z"


def kelp(p: dict[str, str], dark: bool) -> str:
    rng = random.Random(11)
    top = mix(p["background"], p["accent"], 0.22 if dark else 0.28)
    bottom = mix(p["background"], "#000000", 0.45) if dark else mix(p["background"], p["accent"], 0.08)
    layers: dict[int, list[str]] = {0: [], 1: [], 2: []}
    for layer, count in ((0, 22), (1, 14), (2, 8)):
        for i in range(count):
            x0 = rng.uniform(-150, W + 150)
            height = H * rng.uniform(0.45, 0.95) * (0.8 + 0.12 * layer)
            sway = rng.uniform(80, 260)
            ph = rng.random() * math.tau
            pts = [(x0 + sway * math.sin(k / 4.5 + ph) * (k / 14) + 8 * math.sin(k * 0.9 + i),
                    H + 60 - height * k / 14) for k in range(15)]
            width = (20, 34, 52)[layer] * rng.uniform(0.7, 1.2)
            if dark:
                col = mix(p["accent"], p["background"], (0.72, 0.5, 0.25)[layer])
            else:
                col = mix(p["accent"], p["background"], (0.75, 0.5, 0.2)[layer])
            layers[layer].append(f'<path d="{ribbon(pts, width)}" fill="{col}"/>')
    rays = []
    for k in range(6):
        x = W * (0.15 + 0.14 * k) + rng.uniform(-80, 80)
        spread = rng.uniform(160, 360)
        rays.append(f'<polygon points="{x - 40:.0f},0 {x + 40:.0f},0 {x + spread:.0f},{H} {x - spread * 0.4:.0f},{H}" '
                    f'fill="{p["text"] if dark else "#ffffff"}" fill-opacity="{rng.uniform(0.025, 0.06):.3f}"/>')
    bubbles = []
    for _ in range(36):
        r = rng.uniform(5, 18)
        bubbles.append(f'<circle cx="{rng.uniform(0, W):.0f}" cy="{rng.uniform(0, H * 0.8):.0f}" r="{r:.1f}" '
                       f'fill="none" stroke="{p["text"] if dark else "#ffffff"}" '
                       f'stroke-opacity="{rng.uniform(0.12, 0.3):.2f}" stroke-width="3"/>')
    body = f"""<defs>
  <linearGradient id="sea" x1="0" y1="0" x2="0" y2="1">
    <stop offset="0" stop-color="{top}"/><stop offset="1" stop-color="{bottom}"/>
  </linearGradient>
  <filter id="far" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="10"/></filter>
  <filter id="mid" x="-10%" y="-10%" width="120%" height="120%"><feGaussianBlur stdDeviation="3"/></filter>
  {grain_filter()}
</defs>
<g filter="url(#grain)">
<rect width="{W}" height="{H}" fill="url(#sea)"/>
{chr(10).join(rays)}
<g filter="url(#far)">{"".join(layers[0])}</g>
<g filter="url(#mid)">{"".join(layers[1])}</g>
{"".join(layers[2])}
{chr(10).join(bubbles)}
</g>"""
    return svg(W, H, body)


def main() -> None:
    logos = ROOT / "logos"
    logos.mkdir(exist_ok=True)
    (logos / "surfd-mark.svg").write_text(mark_svg())
    (logos / "surfd-wordmark.svg").write_text(wordmark_svg())
    (logos / "surfd-wordmark-dark.svg").write_text(wordmark_svg("#15262f"))
    (logos / "surfd-logo.svg").write_text(logo_svg())
    (logos / "surfd-logo-dark.svg").write_text(logo_svg("#15262f"))
    for name, fn in (("tide", tide), ("driftwood", driftwood), ("kelp", kelp)):
        for variant in ("dark", "light"):
            out = ROOT / "themes" / name / "wallpapers" / f"{name}-{variant}.svg"
            out.write_text(fn(load_palette(name, variant), variant == "dark"))
    print("artwork written")


if __name__ == "__main__":
    main()
