#!/usr/bin/env python3
"""Print the package list of the surfd kickstarts (no groups, no exclusions).

    tools/ks_packages.py [--live] [--arch x86_64] > containers/packages.txt

The bootc Containerfile installs from containers/packages.txt so the
atomic variant and the ISO share one package set. `make check` verifies the
file is in sync with the kickstarts.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

KS = Path(__file__).resolve().parents[1] / "kickstarts"
# Packages that only make sense on live media / with Anaconda, or that a
# bootc base image already provides.
NOT_IN_CONTAINER = {"surfd-live", "anaconda", "anaconda-install-env-deps", "anaconda-live", "dracut-live",
                    "glibc-all-langpacks", "kernel", "kernel-modules", "kernel-modules-extra",
                    "shim-x64", "shim-aa64", "grub2-efi-x64", "grub2-efi-x64-cdboot", "grub2-efi-aa64",
                    "grub2-efi-aa64-cdboot", "grub2-pc", "grub2-pc-modules", "grub2-tools-extra", "efibootmgr"}


def packages(files: list[str]) -> tuple[list[str], list[str], list[str]]:
    pkgs: list[str] = []
    groups: list[str] = []
    excluded: list[str] = []
    for name in files:
        in_pkgs = False
        for line in (KS / name).read_text().splitlines():
            if line.startswith("%packages"):
                in_pkgs = True
                continue
            if line.startswith("%end"):
                in_pkgs = False
                continue
            if not in_pkgs:
                continue
            entry = re.sub(r"#.*", "", line).strip()
            if not entry:
                continue
            if entry.startswith("-"):
                excluded.append(entry[1:])
            elif entry.startswith("@"):
                groups.append(entry[1:])
            elif entry not in pkgs:
                pkgs.append(entry)
    return pkgs, groups, excluded


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--live", action="store_true", help="include live-media packages")
    ap.add_argument("--arch", default="x86_64")
    args = ap.parse_args()
    files = ["surfd-base.ks", "surfd-desktop.ks", f"surfd-boot-{args.arch}.ks"]
    if args.live:
        files.append("surfd-live.ks")
    pkgs, _groups, _excluded = packages(files)
    if not args.live:
        pkgs = [p for p in pkgs if p not in NOT_IN_CONTAINER]
    print("# Generated by tools/ks_packages.py from the kickstarts — do not edit by hand.")
    print("\n".join(pkgs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
